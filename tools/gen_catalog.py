"""Generate the validator's embedded rule catalogue (build step, run by CMake).

    python3 -I gen_catalog.py catalog/rules.json catalog/wcag2.json catalog/matrix.json OUT.cpp OUT.h

Inputs (single source of truth, never edited here):
    catalog/rules.json     canonical rules: id, title, severity, standards, sources, detection
    catalog/wcag2.json     WCAG level of every success criterion per version
    catalog/matrix.json    per target: requirements that need human evaluation (manual_required)

Outputs:
    OUT.cpp   the rule table (RuleInfo), the manual_required lists, the catalogue hash, and the rule ids pre-rendered
              as JSON strings for the report writer
    OUT.h     rule ids and families as constant expressions: R("EQX-...") and the ownership table (rules/ownership.cpp)
              are resolved by the compiler, so no process looks a rule up by name at start-up

Target bitmasks: a rule counts for a target only through a normative mapping; a WCAG success criterion counts
for every WCAG version that contains it, at every target level at or above its own level (docs/STANDARDS.md).
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

LEVELS = {"A": 1, "AA": 2, "AAA": 3}
WCAG_VERSIONS = ("2.0", "2.1", "2.2")
SINGLE_TARGETS = (["pdfua-1", "pdfua-2", "wtpdf-1.0-accessibility", "wtpdf-1.0-reuse"]
                  + [f"wcag-{v}-{lv}" for v in WCAG_VERSIONS for lv in LEVELS])
TARGET_BIT = {t: i for i, t in enumerate(SINGLE_TARGETS)}
SEVERITY = {"error": 0, "warning": 1}
KIND = {"violation": 0, "warning": 1, "recommendation": 2}


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def normative_mask(rule: dict, wcag: dict) -> int:
    mask = 0
    for m in rule.get("standards", []):
        if m.get("obligation") != "normative":
            continue
        std = m["standard"]
        if std == "wcag":
            lv_by_v = wcag.get(m["sc"], {})
            for v in WCAG_VERSIONS:
                lv = lv_by_v.get(v)
                if not lv:
                    continue
                for tlv in LEVELS:
                    if LEVELS[lv] <= LEVELS[tlv]:
                        mask |= 1 << TARGET_BIT[f"wcag-{v}-{tlv}"]
        elif std in TARGET_BIT:
            mask |= 1 << TARGET_BIT[std]
    return mask


def concerns_mask(rule: dict, wcag: dict) -> int:
    mask = 0
    for m in rule.get("standards", []):
        std = m["standard"]
        if std == "wcag":
            for v in WCAG_VERSIONS:
                lv = wcag.get(m["sc"], {}).get(v)
                if not lv:
                    continue
                for tlv in LEVELS:
                    if LEVELS[lv] <= LEVELS[tlv]:
                        mask |= 1 << TARGET_BIT[f"wcag-{v}-{tlv}"]
        elif std in TARGET_BIT:
            mask |= 1 << TARGET_BIT[std]
    return mask


def references(rule: dict, wcag: dict) -> str:
    """Normative references and reference-tool sources of a rule, pre-rendered as compact JSON."""
    stds = []
    for m in rule.get("standards", []):
        e = {"standard": m["standard"], "obligation": m.get("obligation")}
        for k in ("clause", "sc", "matterhorn", "via"):
            if m.get(k):
                e[k] = m[k]
        if m["standard"] == "wcag":
            e["level_by_version"] = wcag.get(m["sc"], {})
        stds.append(e)
    srcs = []
    for s in rule.get("sources", []):
        if s["tool"] == "veraPDF":
            srcs.append({"tool": "veraPDF", "version": s["version"], "profile": s["profile"], "rule": s["rule_id"],
                         "specification": s.get("specification")})
        elif s["tool"] == "EqualDoX":
            srcs.append({"tool": "EqualDoX", "version": s["version"], "check": s.get("check"), "text": s.get("condition_text")})
        else:
            srcs.append({"tool": "PAC", "version": s["version"], "tab": s.get("tab"), "check": s.get("check"),
                         "condition": s.get("condition"), "text": s.get("condition_text")})
    return json.dumps({"standards": stds, "sources": srcs}, ensure_ascii=True, separators=(",", ":"))


def write_if_changed(out: Path, text: str) -> None:
    if not out.exists() or out.read_text("utf-8") != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")


def index_header(rules: list[dict]) -> str:
    """Rule ids (catalogue order) and families for constant evaluation; see catalog.h and ownership.cpp."""
    families = sorted({r.get("family", "") for r in rules})
    family_index = {f: i for i, f in enumerate(families)}
    if len(families) > 0xFFFF:
        raise SystemExit("gen_catalog.py: more than 65535 rule families")
    lines = ["// Generated by tools/gen_catalog.py from catalog/rules.json - do not edit.",
             "// Read in constant evaluation only (consteval functions): none of these tables is part of the binary.",
             "#pragma once", "#include <cstddef>", "#include <cstdint>", "#include <string_view>",
             "namespace eqx::catalog_index {",
             "inline constexpr std::size_t kRuleCount = %d;" % len(rules),
             "// Rule ids in catalogue order (sorted, byte order): the position is the RuleIndex.",
             "inline constexpr std::string_view kRuleIds[kRuleCount] = {"]
    lines += ["  %s," % c_str(r["id"]) for r in rules]
    lines += ["};",
              "inline constexpr std::size_t kFamilyCount = %d;" % len(families),
              "inline constexpr std::string_view kFamilies[kFamilyCount] = {"]
    lines += ["  %s," % c_str(f) for f in families]
    lines += ["};", "// Family of each rule: index into kFamilies.",
              "inline constexpr std::uint16_t kRuleFamily[kRuleCount] = {"]
    idx = [family_index[r.get("family", "")] for r in rules]
    lines += ["  " + ", ".join(str(i) for i in idx[k:k + 24]) + "," for k in range(0, len(idx), 24)]
    lines += ["};", "}  // namespace eqx::catalog_index"]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 5:
        print("usage: gen_catalog.py RULES.json WCAG2.json MATRIX.json OUT.cpp OUT.h", file=sys.stderr)
        return 2
    rules_path, wcag_path, matrix_path, out, out_header = (Path(a) for a in argv)
    raw = rules_path.read_bytes()
    rules = json.loads(raw)["rules"]
    wcag = {c["sc"]: c["level_by_version"] for c in json.loads(wcag_path.read_text("utf-8"))["criteria"]}
    matrix = json.loads(matrix_path.read_text("utf-8"))["targets"]
    rules = sorted(rules, key=lambda r: r["id"])
    lines = ["// Generated by tools/gen_catalog.py from catalog/rules.json - do not edit.",
             '#include "rules/catalog.h"', "namespace eqx {", "namespace {", "const RuleInfo kRules[] = {"]
    for r in rules:
        if r.get("automation") not in ("automatic", "partial") or r.get("excluded"):
            required = 0
        else:
            required = 1
        lines.append("  {%s, %s, %d, %d, %du, %du, %d, %s, %s, %s}," % (
            c_str(r["id"]), c_str(r["title"]), SEVERITY[r["severity"]], KIND[r["kind"]],
            normative_mask(r, wcag), concerns_mask(r, wcag), required,
            c_str(r.get("family", "")), c_str(r.get("detection") or ""), c_str(references(r, wcag))))
    lines.append("};")
    for t in SINGLE_TARGETS:
        ids = matrix[t]["manual_required"]
        lines.append("const char* const kManual_%s[] = {%s nullptr};" % (
            t.replace("-", "_").replace(".", "_"), "".join(c_str(i) + ", " for i in sorted(ids))))
    lines.append("}  // namespace")
    lines.append("const RuleInfo* catalog_rules(std::size_t* n) { *n = sizeof(kRules) / sizeof(kRules[0]); return kRules; }")
    lines.append("const char* const* catalog_manual(int target) {")
    lines.append("  switch (target) {")
    for i, t in enumerate(SINGLE_TARGETS):
        lines.append("    case %d: return kManual_%s;" % (i, t.replace("-", "_").replace(".", "_")))
    lines.append("    default: return nullptr;\n  }\n}")
    lines.append("const char* catalog_sha256() { return %s; }" % c_str(hashlib.sha256(raw).hexdigest()))
    # The ids as the report writes them: "ID","ID",... in catalogue order, with the offset of each id's opening quote.
    # A run of consecutive rules is then one copy. An id that JSON would have to escape cannot be pre-rendered this way.
    for r in rules:
        if json.dumps(r["id"], ensure_ascii=False) != '"%s"' % r["id"] or not r["id"].isascii() or not r["id"].isprintable():
            raise SystemExit("gen_catalog.py: rule id %r needs JSON escaping" % r["id"])
    offsets, pos = [], 0
    for r in rules:
        offsets.append(pos)
        pos += len(r["id"]) + 3   # quotes and the comma
    offsets.append(pos)
    lines.append("namespace {")
    lines.append("const char kIdsJson[] =")
    lines += ["  %s" % c_str('"%s",' % r["id"]) for r in rules]
    lines.append("  ;")
    lines.append("const std::uint32_t kIdsJsonOffset[] = {")
    lines += ["  " + ", ".join(str(o) for o in offsets[k:k + 16]) + "," for k in range(0, len(offsets), 16)]
    lines.append("};")
    lines.append("}  // namespace")
    lines.append("std::string_view catalog_ids_json(RuleIndex first, RuleIndex last) {")
    lines.append("  if (first >= last) return {};")
    lines.append("  return std::string_view(kIdsJson + kIdsJsonOffset[first], kIdsJsonOffset[last] - kIdsJsonOffset[first] - 1);")
    lines.append("}")
    lines.append("}  // namespace eqx")
    write_if_changed(out, "\n".join(lines) + "\n")
    write_if_changed(out_header, index_header(rules))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
