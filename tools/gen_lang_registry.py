"""Generates src/rules/document/lang_registry_data.cpp from the IANA Language Subtag Registry.

    python3 -I tools/gen_lang_registry.py REGISTRY_FILE OUTPUT_CPP

REGISTRY_FILE is a local copy of
    https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry
(downloaded once, never at build or run time). The output records the source URL, the registry's File-Date
and the sha256 of the copy that was used.

What is extracted (used by the PAC 26.1 "ValidLanguage" emulation of the document module):
  * every subtag of Type "language" that is a single subtag; ranges such as "qaa..qtz" are NOT expanded,
    because PAC 26.1 reports the private-use language 'qaa' as a syntax error (probe p20);
  * every Tag of Type "grandfathered" (lower-cased), e.g. "i-klingon", "en-GB-oed".
The registry is read as plain data; nothing in it is executed.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

URL = "https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry"


def records(text: str):
    """Yields one dict per record (field -> list of values); continuation lines are folded."""
    for block in text.split("\n%%"):
        fields: dict[str, list[str]] = {}
        last = None
        for line in block.splitlines():
            if not line.strip():
                continue
            if line[0] in " \t" and last is not None:
                fields[last][-1] += " " + line.strip()
                continue
            if ":" not in line:
                continue
            key, _, value = line.partition(":")
            last = key.strip()
            fields.setdefault(last, []).append(value.strip())
        if fields:
            yield fields


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    src, out = Path(argv[0]), Path(argv[1])
    raw = src.read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    text = raw.decode("utf-8")
    file_date = None
    languages: set[str] = set()
    grandfathered: set[str] = set()
    for rec in records(text):
        if "File-Date" in rec and file_date is None:
            file_date = rec["File-Date"][0]
            continue
        kind = rec.get("Type", [""])[0]
        if kind == "language":
            sub = rec.get("Subtag", [""])[0]
            if sub and ".." not in sub:
                languages.add(sub.lower())
        elif kind == "grandfathered":
            tag = rec.get("Tag", [""])[0]
            if tag:
                grandfathered.add(tag.lower())
    if not file_date or not languages:
        print("not a language subtag registry", file=sys.stderr)
        return 1
    for s in languages | grandfathered:
        if not all(c.isascii() and (c.isalnum() or c == "-") for c in s):
            print(f"unexpected subtag {s!r}", file=sys.stderr)
            return 1

    def array(name: str, items: set[str]) -> str:
        body = []
        line = "   "
        for s in sorted(items):
            tok = f' "{s}",'
            if len(line) + len(tok) > 116:
                body.append(line)
                line = "   "
            line += tok
        body.append(line)
        return f"const char* const {name}[] = {{\n" + "\n".join(body) + "\n};\n" \
               f"const std::size_t {name}Count = sizeof({name}) / sizeof({name}[0]);\n"

    cpp = (
        "// GENERATED by tools/gen_lang_registry.py - do not edit.\n"
        f"// Source: {URL}\n"
        f"// File-Date: {file_date}\n"
        f"// sha256: {sha}\n"
        "// Language subtags (Type: language, ranges not expanded) and grandfathered tags, lower case, sorted.\n"
        "#include <cstddef>\n\n"
        "namespace eqx::langreg {\n\n"
        f'extern const char* const kSourceUrl = "{URL}";\n'
        f'extern const char* const kFileDate = "{file_date}";\n'
        f'extern const char* const kSha256 = "{sha}";\n\n'
        + "extern " + array("kLanguages", languages) + "\n"
        + "extern " + array("kGrandfathered", grandfathered) + "\n"
        "}  // namespace eqx::langreg\n"
    )
    # 'extern const std::size_t ...Count' needs the extern on the count too.
    cpp = cpp.replace("\nconst std::size_t", "\nextern const std::size_t")
    out.write_text(cpp, "utf-8")
    print(f"{out}: {len(languages)} language subtags, {len(grandfathered)} grandfathered tags, File-Date {file_date}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
